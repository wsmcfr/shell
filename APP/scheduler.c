/**
 *******************************************************************************
 * @file    scheduler.c
 * @brief   简易任务调度器实现
 * @details 此模块实现了一个基于时间片的协作式任务调度器。
 *          调度器不使用操作系统，而是通过轮询方式检查各任务的执行时间，
 *          适合资源受限的嵌入式系统。
 *
 * @version 1.0
 * @date    2024
 * @author  Shell Team
 *
 * @par 调度器工作原理:
 *      1. 每个任务定义执行周期（毫秒）
 *      2. 主循环中调用scheduler_run()
 *      3. scheduler_run()检查每个任务是否到达执行时间
 *      4. 如果到达，执行任务并更新上次执行时间
 *
 *      时间线示例：
 *      T=0ms   [LED] [KEY] [UART] [LCD]    // 初始化，所有任务执行
 *      T=1ms   [LED]                        // 只有LED（周期1ms）执行
 *      T=10ms  [LED] [KEY] [UART]           // LED、KEY、UART执行
 *      T=100ms [LED] [KEY] [UART] [LCD]     // 所有任务再次执行
 *
 * @par 特点:
 *      - 非抢占式：任务一旦开始执行，会运行到完成
 *      - 静态配置：任务在编译时确定
 *      - 低开销：不需要任务堆栈
 *      - 简单可靠：代码量小，易于理解和维护
 *
 * @warning 任务函数应尽快返回，长时间执行会影响其他任务的响应性
 *******************************************************************************
 */

#include "scheduler.h"

/*===========================================================================*/
/*                              类型定义                                       */
/*===========================================================================*/

/**
 * @brief   任务结构体
 * @details 定义单个任务的所有属性
 */
typedef struct {
    void (*task_func)(void);    /**< 任务函数指针 */
    uint32_t rate_ms;           /**< 任务执行周期（毫秒） */
    uint32_t last_run;          /**< 上次执行时间（毫秒） */
} task_t;

/*===========================================================================*/
/*                              全局变量                                       */
/*===========================================================================*/

/**
 * @brief   任务数量
 * @details 由scheduler_init()计算并设置
 */
uint8_t task_num;

/**
 * @brief   任务列表（静态配置）
 * @details 定义系统中所有需要周期性执行的任务
 *
 * @par 任务配置说明:
 *      {任务函数, 执行周期(ms), 初始上次执行时间}
 *
 * @par 添加新任务:
 *      在数组中添加一行: {新任务函数, 执行周期, 0}
 *
 * @par 任务执行周期选择建议:
 *      - 1ms:    高实时性要求（如LED刷新）
 *      - 10ms:   中等实时性（如按键扫描、Shell处理）
 *      - 20ms:   较低实时性（如ADC采样）
 *      - 50ms:   低实时性（如频率测量）
 *      - 100ms:  用户界面更新（如LCD显示）
 */
static task_t scheduler_task[] =
{
    /* 任务函数     执行周期   上次执行时间 */
    {led_proc,      1,         0},  /**< LED刷新任务，1ms周期，高优先级 */
    {key_proc,      10,        0},  /**< 按键扫描任务，10ms周期 */
    {lcd_proc,      100,       0},  /**< LCD显示任务，100ms周期 */
    {uart_proc,     10,        0},  /**< Shell命令处理任务，10ms周期 */
    {adc_proc,      20,        0},  /**< ADC数据处理任务，20ms周期 */
    {rtc_proc,      10,        0},  /**< RTC时间读取任务，10ms周期 */
    {ic_proc,       50,        0},  /**< 输入捕获处理任务，50ms周期 */
};

/*===========================================================================*/
/*                              函数实现                                       */
/*===========================================================================*/

/**
 * @brief   调度器初始化
 * @details 计算任务数量，为scheduler_run()准备
 *
 * @note    必须在主循环之前调用一次
 *          此函数只计算任务数量，不执行任何任务
 *
 * @par 调用位置:
 *      通常在main()函数的初始化部分调用
 *
 * @code
 * int main(void)
 * {
 *     // 硬件初始化...
 *     scheduler_init();
 *
 *     while(1)
 *     {
 *         scheduler_run();
 *     }
 * }
 * @endcode
 */
void scheduler_init(void)
{
    /*
     * 计算任务数量
     * sizeof(scheduler_task) 返回整个数组的字节大小
     * sizeof(task_t) 返回单个任务结构体的字节大小
     * 两者相除得到任务数量
     */
    task_num = sizeof(scheduler_task) / sizeof(task_t);
}

/**
 * @brief   调度器运行函数
 * @details 检查所有任务，执行到达执行时间的任务
 *
 * @note    此函数应在主循环中不断调用
 *          每次调用会遍历所有任务，检查是否需要执行
 *
 * @par 执行逻辑:
 *      1. 获取当前系统时间 (HAL_GetTick())
 *      2. 遍历任务列表
 *      3. 对每个任务：
 *         - 计算距离上次执行的时间
 *         - 如果 >= 任务周期，则执行任务
 *         - 更新任务的上次执行时间
 *
 * @par 时间处理:
 *      使用 >= 而不是 == 比较，这样即使主循环有些延迟，
 *      也不会错过任务执行。但如果延迟过长，任务只会执行一次，
 *      不会累积执行多次。
 *
 * @warning 如果某个任务执行时间过长，会影响其他任务的调度精度
 *          每个任务应尽快完成并返回
 */
void scheduler_run(void)
{
    /* 遍历所有注册的任务 */
    for (uint8_t i = 0; i < task_num; i++)
    {
        /* 获取当前系统时间（毫秒） */
        uint32_t now_time = HAL_GetTick();

        /*
         * 检查任务是否到达执行时间
         * 条件: 当前时间 >= (上次执行时间 + 执行周期)
         * 即: 当前时间 - 上次执行时间 >= 执行周期
         */
        if (now_time >= scheduler_task[i].rate_ms + scheduler_task[i].last_run)
        {
            /* 更新任务的上次执行时间为当前时间 */
            scheduler_task[i].last_run = now_time;

            /* 执行任务函数 */
            scheduler_task[i].task_func();
        }
    }
}
